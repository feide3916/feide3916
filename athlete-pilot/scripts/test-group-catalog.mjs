import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import assert from 'node:assert/strict';
const load=file=>{const context=vm.createContext({exports:{},Map,Set,Array,Number,String,Object});vm.runInContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);return context.exports;};
const catalog=load('app/exercise-catalog.ts'),groups=load('app/group-sets.ts');
assert.equal(catalog.canonicalExercise('杠铃深蹲'),'杠铃深蹲（Barbell Back Squat）');
assert.equal(catalog.canonicalExercise('Romanian Deadlift'),'罗马尼亚硬拉（Romanian Deadlift）');
assert.ok(catalog.sameExercise('箱式跳跃','箱式跳跃（Box Jump）'));
assert.ok(!catalog.sameExercise('杠铃深蹲','前蹲'));
const names=catalog.libraryExercises(['杠铃深蹲','自定义器械动作','壶铃摇摆']);
assert.equal(names.filter(x=>x==='杠铃深蹲（Barbell Back Squat）').length,1);
assert.ok(!names.includes('杠铃深蹲'));
assert.ok(names.includes('自定义器械动作'));
assert.ok(names.length>=50);
const row=(load='')=>({reps:'5',load,actualReps:'',actualLoad:'',actualSpeed:''});
const a={id:'a',group:'A',sets:[row('60'),row('65')]},b={id:'b',group:'A',sets:[row('20'),row('25')]},c={id:'c',group:'B',sets:[row('10')]};
assert.equal(groups.groupSetCount([a,b,c],'A'),2);
assert.equal(groups.groupSetCount([a,b,c],'B'),1);
assert.equal(groups.groupSetCount([a,{...b,sets:[row('20')]}],'A'),0);
const grown=groups.resizeGroupSets([a,b,c],'A',4,()=>row());
assert.equal(grown[0].sets.length,4);
assert.equal(grown[1].sets.length,4);
assert.equal(grown[2].sets.length,1);
assert.equal(grown[0].sets[0].load,'60');
assert.equal(grown[0].sets[2].load,'65');
assert.ok(groups.removedSetHasData(grown,'A',2));
assert.equal(groups.removedSetHasData([{...a,sets:[row(),row(),row()]}],'A',2),false);
assert.equal(groups.resizeGroupSets(grown,'A',2,()=>row())[0].sets[1].load,'65');
console.log('Bilingual aliases retain old training history; group counts keep earlier weights and protect rows before shrinking.');
